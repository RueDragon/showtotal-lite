const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const {validateSettings,priceText,yesterday} = require('../core')
const {parseEnv,saveEnv,loadEnv} = require('../env')
test('HTTPS and key validation',()=>{
  const result=validateSettings({baseUrl:'https://example.com/api/',token:'Bearer test-key',orgPath:' Team '})
  assert.deepEqual(result,{baseUrl:'https://example.com/api',token:'test-key',orgPath:'Team'})
  for(const baseUrl of ['http://example.com','https://user:pass@example.com','https://example.com?key=x']) assert.throws(()=>validateSettings({baseUrl,token:'test'}))
  assert.throws(()=>validateSettings({baseUrl:'https://example.com',token:'x\ny'}))
})
test('minimum discount applies to all token rates',()=>{
  assert.equal(priceText({pricing:{input_price:16,output_price:80,cache_hit_price:0.8},standard_discount:{min_vendor_discount_rate:0.03,max_vendor_discount_rate:0.1}}),'0.48/2.4/0.024')
  assert.equal(priceText({pricing:{input_price:0.8,output_price:4,cache_price:0.08},standard_discount:{min_vendor_discount_rate:0.03}}),'0.024/0.12/0.0024')
  assert.equal(priceText({pricing:{input_price:2,output_price:8,cache_price:0.04},standard_discount:{min_vendor_discount_rate:0}}),'0/0/0')
  assert.equal(priceText({pricing:{input_price:2,output_price:8,cache_price:0.04}}),'2/8/0.04')
  assert.equal(priceText({pricing:{input_price:2}}),'')
})
test('yesterday uses Shanghai calendar across year boundary',()=>{
  assert.equal(yesterday(new Date('2026-01-01T00:00:00Z')),'2025-12-31')
  assert.equal(yesterday(new Date('2026-10-08T16:01:00Z')),'2026-10-08')
})
test('env parsing and round trip handles special characters',t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'showtotal-test-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
  const file=path.join(root,'.env'),settings={baseUrl:'https://example.com/api',token:'key#special"\\',orgPath:'Example / Team'}
  saveEnv(file,settings);assert.deepEqual(loadEnv(file),settings)
  assert.equal(parseEnv("# comment\nSHOWTOTAL_API_KEY='abc#x'\n").token,'abc#x')
  assert.equal(loadEnv(path.join(root,'missing')),null)
})
test('packaging and UI cannot embed private configuration',()=>{
  const pkg=require('../package.json')
  assert.ok(pkg.build.files.includes('!.env'))
  const html=fs.readFileSync(path.join(__dirname,'../index.html'),'utf8')
  assert.ok(html.includes("connect-src 'none'"))
  const main=fs.readFileSync(path.join(__dirname,'../main.js'),'utf8')
  assert.ok(main.includes('nodeIntegration:false'))
  assert.ok(main.includes('contextIsolation:true'))
})
